_SORTED_NAMES = sorted(set(_COUNTRY_NAMES), key=len, reverse=True)


def extract_country(*texts: str) -> str:
    """주어진 텍스트(들)에서 국가명을 찾아 반환한다. 못 찾으면 빈 문자열."""
    combined = " ".join(t for t in texts if t)
    if not combined:
        return ""
    for name in _SORTED_NAMES:
        if name in combined:
            # 표기 통일 (티모르레스테 -> 동티모르, 터키 -> 튀르키예)
            if name == "티모르레스테":
                return "동티모르"
            if name == "터키":
                return "튀르키예"
            return name
    return ""
